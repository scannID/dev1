package com.scanny.entity;

import com.scanny.model.enums.RentPaymentMethod;
import com.scanny.model.enums.RentPaymentStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.Instant;

/**
 * A single payment recorded against a {@link RentCharge}.
 *
 * <p>For manually-recorded payments (cash, bank, MoMo transfer that the manager
 * observed) the {@code status} is set to {@code Completed} immediately and the
 * {@code recordedBy} field captures the account that logged it.
 *
 * <p>For future gateway-initiated payments (e.g. MoMo push) the row starts as
 * {@code Pending} and is updated via the callback/webhook flow.
 */
@Entity
@Table(name = "rent_payments")
public class RentPayment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "charge_id", nullable = false)
    private RentCharge charge;

    /**
     * Unique transaction reference.
     * For manual payments: generated by {@link com.scanny.rent.gateway.ManualGateway}.
     * For gateway payments: provided by the external gateway.
     */
    @Column(name = "transaction_ref", nullable = false, unique = true, length = 128)
    private String transactionRef;

    /** Amount paid in the charge's currency minor units (whole-number UGX). */
    @Column(nullable = false)
    private long amount;

    @Column(nullable = false, length = 8)
    private String currency = "UGX";

    /** The method by which this payment was made. */
    @Enumerated(EnumType.STRING)
    @Column(name = "payment_method", nullable = false, length = 16)
    private RentPaymentMethod paymentMethod = RentPaymentMethod.MOMO;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private RentPaymentStatus status = RentPaymentStatus.Pending;

    @Column(name = "paid_at")
    private Instant paidAt;

    @Column(name = "failed_at")
    private Instant failedAt;

    @Column(name = "failure_reason", columnDefinition = "TEXT")
    private String failureReason;

    /**
     * Account ID of the manager who recorded this payment.
     * Null for gateway-initiated (tenant self-service) payments.
     */
    @Column(name = "recorded_by", length = 64)
    private String recordedBy;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    @Column(name = "created_by", length = 255)
    private String createdBy = "system";

    @Column(name = "updated_at")
    private Instant updatedAt;

    // ── Getters / setters ────────────────────────────────────────────────────

    public Long getId()                              { return id; }
    public void setId(Long id)                       { this.id = id; }

    public RentCharge getCharge()                    { return charge; }
    public void setCharge(RentCharge c)              { this.charge = c; }

    public String getTransactionRef()                { return transactionRef; }
    public void setTransactionRef(String r)          { this.transactionRef = r; }

    public long getAmount()                          { return amount; }
    public void setAmount(long a)                    { this.amount = a; }

    public String getCurrency()                      { return currency; }
    public void setCurrency(String c)                { this.currency = c != null ? c : "UGX"; }

    public RentPaymentMethod getPaymentMethod()      { return paymentMethod; }
    public void setPaymentMethod(RentPaymentMethod m){ this.paymentMethod = m != null ? m : RentPaymentMethod.MOMO; }

    public RentPaymentStatus getStatus()             { return status; }
    public void setStatus(RentPaymentStatus s)       { this.status = s; }

    public Instant getPaidAt()                       { return paidAt; }
    public void setPaidAt(Instant t)                 { this.paidAt = t; }

    public Instant getFailedAt()                     { return failedAt; }
    public void setFailedAt(Instant t)               { this.failedAt = t; }

    public String getFailureReason()                 { return failureReason; }
    public void setFailureReason(String r)           { this.failureReason = r; }

    public String getRecordedBy()                    { return recordedBy; }
    public void setRecordedBy(String by)             { this.recordedBy = by; }

    public Instant getCreatedAt()                    { return createdAt; }
    public void setCreatedAt(Instant t)              { this.createdAt = t; }

    public String getCreatedBy()                     { return createdBy; }
    public void setCreatedBy(String by)              { this.createdBy = by != null ? by : "system"; }

    public Instant getUpdatedAt()                    { return updatedAt; }
    public void setUpdatedAt(Instant t)              { this.updatedAt = t; }
}
